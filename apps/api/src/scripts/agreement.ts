import "dotenv/config";
import { randomUUID } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { scoreField } from "@repo/scoring";
import { fieldRulesSchema } from "@repo/types";
import { prisma } from "../db/prisma";
import { runWithRequestContext } from "../utils/requestContext";
import { closePubSub } from "../utils/events/pubsub";
import { closeAll } from "./closeAll";
import { flag, resolveOrgId } from "./resolveOrg";

/*
  pnpm --filter api exec tsx src/scripts/agreement.ts --task job-postings \
    --export ../../cases/job-postings/data/second-label.jsonl --report ../../cases/job-postings/data/AGREEMENT.md
  Second labels vs primary labels, scored by @repo/scoring (the exact functions models face). Writes the
  second labels as {id, expected} lines and a generated AGREEMENT.md: n, per-field agreement, every disagreement.
 */
const main = async () => {
    const args = process.argv.slice(2);
    const slug = flag(args, "--task");
    if (!slug) throw new Error("Usage: agreement --task <slug> [--export file.jsonl] [--report AGREEMENT.md] [--org id | --email you]");
    const orgId = await resolveOrgId({ orgId: flag(args, "--org"), email: flag(args, "--email") });
    await runWithRequestContext({ orgId, requestId: `cli-${randomUUID()}` }, async () => {
        const task = await prisma.task.findFirst({ where: { slug } });
        if (!task) throw new Error(`No task "${slug}" in this workspace`);
        const fields = fieldRulesSchema.parse(task.fields);
        const examples = await prisma.example.findMany({ where: { taskId: task.id, secondLabelById: { not: null } }, orderBy: { ref: "asc" } });
        const rows = fields.map((rule) => {
            const scores = examples.map((e) => ({ ref: e.ref, s: scoreField(rule, e.secondLabel as Record<string, unknown>, e.expected as Record<string, unknown>)[0] }));
            return {
                key: rule.key,
                mean: scores.length ? scores.reduce((a, b) => a + b.s.score, 0) / scores.length : null,
                disagreements: scores.filter((x) => x.s.score !== 1).map((x) => {
                    const e = examples.find((ex) => ex.ref === x.ref)!;
                    return { ref: x.ref, reason: x.s.reason, primary: (e.expected as Record<string, unknown>)[rule.key], second: (e.secondLabel as Record<string, unknown>)[rule.key] };
                }),
            };
        });
        const md = [
            `# Label agreement: ${task.name}`,
            "",
            `Generated by \`agreement.ts\` (never typed). n = ${examples.length} double-labelled examples (${examples.filter((e) => e.split === "dev").length} dev, ${examples.filter((e) => e.split === "test").length} test). Second labels are scored against the primary labels with the same scorer as model outputs (skills: mean F1).`,
            "",
            "| Field | Agreement | Disagreements |",
            "| --- | ---: | ---: |",
            ...rows.map((r) => `| ${r.key} | ${r.mean == null ? "n/a" : `${(r.mean * 100).toFixed(1)} %`} | ${r.disagreements.length} |`),
            "",
            "## Disagreements",
            "",
            ...(rows.every((r) => r.disagreements.length === 0) ? ["None."] : rows.flatMap((r) => r.disagreements.map((d) => `- \`${d.ref}\` · ${r.key} (${d.reason}): primary \`${JSON.stringify(d.primary)}\` · second \`${JSON.stringify(d.second)}\``))),
            "",
        ].join("\n");
        const exportFile = flag(args, "--export");
        if (exportFile) await writeFile(exportFile, examples.map((e) => JSON.stringify({ id: e.ref, expected: e.secondLabel })).join("\n") + (examples.length ? "\n" : ""));
        const report = flag(args, "--report");
        if (report) await writeFile(report, md);
        console.log(report ? `wrote ${report} (n = ${examples.length})` : md);
    });
};
main()
    .catch((e) => {
        console.error(e.message ?? e);
        process.exitCode = 1;
    })
    .finally(async () => {
        await closePubSub();
        await closeAll();
    });

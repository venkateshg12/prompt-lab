import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { aggregateVariant, type ResultLite } from "../aggregate";
import type { FieldRule } from "@repo/types";

/*
  Parity with the Playbook's importer. `fixtures/run.jsonl` is a copy of the Playbook's own importer fixture,
  and `fixtures/parity-ref.json` holds the values its promptLabRows() produced for it (generated by running
  the Playbook's code, not by hand). If either side changes a definition, this test or the Playbook's goes red.
 */
const lines = readFileSync(path.resolve(__dirname, "fixtures/run.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const ref = JSON.parse(readFileSync(path.resolve(__dirname, "fixtures/parity-ref.json"), "utf8")) as {
    stats: { v: string; n: number; repeats: number; errors: number; skipped: number }[];
    rows: { v: string; metric: string; value: number; lo: number; hi: number; n: number; cost: number; p95: number }[];
};
// The fixture only has two scored fields; the metrics under test don't need the task's full rule list.
const fields: FieldRule[] = [
    { kind: "enum", key: "remote", values: ["a", "b"] },
    { kind: "money", key: "stipend_or_salary", tolerance: 0.05, currencies: ["INR"] },
];

describe("parity with the Playbook importer", () => {
    for (const stat of ref.stats) {
        it(`${stat.v}: n, repeats, errors and every metric match to the last digit`, () => {
            const rows: ResultLite[] = lines
                .filter((l) => l.promptVersion === stat.v)
                .map((l) => ({ ...l, exampleId: l.exampleId, repeat: l.repeat }));
            const s = aggregateVariant(rows, fields);
            expect(s).toMatchObject({ n: stat.n, repeats: stat.repeats, errors: stat.errors, skipped: stat.skipped });
            const metrics = ref.rows.filter((r) => r.v === stat.v);
            expect(metrics.length).toBeGreaterThan(0);
            for (const m of metrics) {
                const got = s.metrics[m.metric]!;
                expect(got.value, `${m.metric} value`).toBe(m.value);
                expect(got.ci[0], `${m.metric} ci low`).toBe(m.lo);
                expect(got.ci[1], `${m.metric} ci high`).toBe(m.hi);
                expect(s.costUsdPer100, "cost per 100").toBe(m.cost);
                expect(s.p95Ms, "p95").toBe(m.p95);
            }
        });
    }
});
